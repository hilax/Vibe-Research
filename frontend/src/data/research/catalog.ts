const GRADE_ORDER = { A: 0, B: 1, C: 2, D: 3, E: 4 } as const;

function conservativeEvidenceGrade(sourceIds: string[]): ResearchRecord["evidenceGrade"] {
  return sourceIds.reduce<ResearchRecord["evidenceGrade"]>((grade, id) => {
    const sourceGrade = researchSourceById.get(id)?.grade ?? "E";
    return GRADE_ORDER[sourceGrade] > GRADE_ORDER[grade] ? sourceGrade : grade;
  }, "A");
}

